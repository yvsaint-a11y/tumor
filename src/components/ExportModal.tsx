import React, { useState } from 'react';
import { ScanReport } from '../types/scanner.js';
import { X, Copy, Check, Download, FileText, Code } from 'lucide-react';

interface ExportModalProps {
  isOpen: boolean;
  onClose: () => void;
  report: ScanReport | null;
}

export const ExportModal: React.FC<ExportModalProps> = ({ isOpen, onClose, report }) => {
  const [copied, setCopied] = useState(false);
  const [format, setFormat] = useState<'markdown' | 'json'>('markdown');

  if (!isOpen || !report) return null;

  const generateMarkdown = (): string => {
    const cov = report.coverage;
    const totalScannable = cov?.totalScannableFiles || cov?.totalFilesInRepo || report.stack.totalFilesScanned;
    const covPercent = totalScannable > 0
      ? Math.round(((cov?.filesScanned || report.stack.totalFilesScanned) / totalScannable) * 100)
      : 100;

    return `# Tumorr Health Audit Report: ${report.repoName}
**Score:** ${report.rubric.score}/100 | **Grade:** ${report.rubric.grade} (${report.rubric.verdict}) ${cov?.isPartial ? '[PARTIAL SCAN]' : '[COMPLETE SCAN]'}  
**Scanned At:** ${new Date(report.scannedAt).toUTCString()}  
**Commit SHA:** \`${report.commitSha || 'latest'}\`  
**Stack Detected:** ${report.stack.languages.join(', ')} (${report.stack.frameworks.join(', ') || 'Vanilla'})  
**Coverage:** Scanned ${cov?.filesScanned || report.stack.totalFilesScanned} of ${totalScannable} scannable files (${covPercent}% coverage)  
${cov?.nonScannableSkipped !== undefined ? `**Non-Scannable Files Skipped:** ${cov.nonScannableSkipped} files (media, binary, ignored folders)  \n` : ''}${cov?.notes && cov.notes.length > 0 ? `**Coverage Notes:** ${cov.notes.join('; ')}  \n` : ''}**Findings By Effective Tier:** Critical: ${report.rubric.counts.critical} (-${report.rubric.deductions.critical} pts) | High: ${report.rubric.counts.high} (-${report.rubric.deductions.high} pts) | Medium: ${report.rubric.counts.medium} (-${report.rubric.deductions.medium} pts) | Low: ${report.rubric.counts.low} (-${report.rubric.deductions.low} pts)  
**Scoring Rubric:** Standard: Critical (-25), High (-15), Medium (-8), Low (-3). Dev dependency vulnerabilities deduct 1 severity tier lower (e.g. High becomes Medium: -8 pts).  
${
  cov?.isPartial
    ? `> **Notice:** Partial scan. Skipped: ${cov.skippedSummary.overCap} over cap, ${cov.skippedSummary.tooLarge} too large. This score may be optimistic.\n`
    : ''
}
---

## Executive Summary (Plain English)
${report.executiveSummary.overview}

### Top 3 Things to Fix First:
${report.executiveSummary.topThreeFixes.map((f, i) => `${i + 1}. ${f}`).join('\n')}

### Vibe Coding Pattern Insight:
${report.executiveSummary.vibeAppInsight}

---

## Detailed Findings (${report.findings.length} Total)
${report.findings
  .map(
    (f, idx) => {
      const safeEvidence = (f.evidence || '').replace(/```/g, '` ` `');
      const safePrompt = (f.explanation?.aiFixPrompt || '').replace(/`/g, "'");
      return `
### ${idx + 1}. [${(f.effectiveSeverity || f.severity).toUpperCase()}] ${f.title}
- **File:** \`${f.file}:${f.line}\`
- **Rule ID:** \`${f.ruleId}\`
- **Effective Severity:** ${(f.effectiveSeverity || f.severity).toUpperCase()}${f.effectiveSeverity && f.effectiveSeverity !== f.severity ? ` (discounted from ${f.severity.toUpperCase()} for ${f.depScope === 'dev' ? 'dev dependency' : 'scope'})` : ''}
- **Dependency Scope:** ${f.depScope ? (f.depScope === 'dev' ? 'dev dependency (deducted 1 severity tier lower)' : 'runtime dependency') : 'N/A'}
- **Explanation Source:** ${f.explanation?.source === 'gemini' ? 'Gemini AI' : 'Deterministic Fallback Rule'}
- **Confidence:** ${f.confidence === 'low' ? 'Low (Range minimum inference)' : f.confidence === 'medium' ? 'Medium (Registry max satisfying)' : 'High (Verified)'}
- **Plain-English Risk:** ${f.explanation?.plainEnglishRisk || f.descriptionRaw}
- **Recommended Action:** ${f.explanation?.nextStep || 'Inspect and fix this file.'}
- **Code Evidence:**
\`\`\`
${safeEvidence}
\`\`\`
${safePrompt ? `\n> **Prompt for Cursor / Lovable:** \`${safePrompt}\`` : ''}
`;
    }
  )
  .join('\n---\n')}

---
*Report generated by Tumorr adhering to strict Agent Rules (Deterministic auditing + Gemini plain-English translations).*
`;
  };

  const content = format === 'markdown' ? generateMarkdown() : JSON.stringify(report, null, 2);

  const handleCopy = () => {
    navigator.clipboard.writeText(content);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  const handleDownload = () => {
    const filename = `tumorr-${report.repoName.replace('/', '_')}_health_audit.${format === 'markdown' ? 'md' : 'json'}`;
    const blob = new Blob([content], { type: format === 'markdown' ? 'text/markdown' : 'application/json' });
    const url = URL.createObjectURL(blob);
    const a = document.createElement('a');
    a.href = url;
    a.download = filename;
    a.click();
    URL.revokeObjectURL(url);
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/75 backdrop-blur-sm">
      <div className="bg-[#1D1713] border border-[#382D25] rounded-2xl max-w-2xl w-full p-6 shadow-2xl relative max-h-[90vh] flex flex-col">
        <button
          onClick={onClose}
          className="absolute top-4 right-4 p-2 text-[#A39382] hover:text-[#F2E9DF] rounded-lg hover:bg-[#382D25]/40 transition"
        >
          <X className="w-5 h-5" />
        </button>

        <div className="flex items-center gap-3 mb-4">
          <div className="p-2 rounded-xl bg-[#382D25]/40 border border-[#382D25] text-[#F2E9DF]">
            <Download className="w-5 h-5" />
          </div>
          <div>
            <h3 className="text-base font-bold text-[#F2E9DF]">Export health report</h3>
            <p className="text-xs text-[#A39382]">Download or copy report with coverage and source transparency</p>
          </div>
        </div>

        {/* Format Selector */}
        <div className="flex items-center gap-2 mb-3">
          <button
            onClick={() => setFormat('markdown')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition ${
              format === 'markdown' ? 'bg-[#F2E9DF] text-[#14100D]' : 'bg-[#14100D] border border-[#382D25] text-[#A39382] hover:text-[#F2E9DF]'
            }`}
          >
            <FileText className="w-3.5 h-3.5" />
            Markdown report (.md)
          </button>
          <button
            onClick={() => setFormat('json')}
            className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg text-xs font-semibold transition ${
              format === 'json' ? 'bg-[#F2E9DF] text-[#14100D]' : 'bg-[#14100D] border border-[#382D25] text-[#A39382] hover:text-[#F2E9DF]'
            }`}
          >
            <Code className="w-3.5 h-3.5" />
            Raw data (.json)
          </button>
        </div>

        {/* Code Content Preview */}
        <div className="flex-1 min-h-[250px] p-3 rounded-xl bg-[#14100D] border border-[#382D25] overflow-y-auto font-mono text-xs text-[#F2E9DF]">
          <pre className="whitespace-pre-wrap">{content}</pre>
        </div>

        {/* Actions Footer */}
        <div className="mt-4 pt-4 border-t border-[#382D25] flex items-center justify-between">
          <span className="text-xs text-[#A39382]">Ready to paste into Notion, GitHub issues, or Slack</span>
          <div className="flex items-center gap-2">
            <button
              onClick={handleCopy}
              className="flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-xl bg-[#14100D] border border-[#382D25] hover:bg-[#382D25]/40 text-[#F2E9DF] transition"
            >
              {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
              <span>{copied ? 'Copied' : 'Copy'}</span>
            </button>
            <button
              onClick={handleDownload}
              className="flex items-center gap-1.5 px-3.5 py-1.5 text-xs font-medium rounded-xl bg-[#F2E9DF] hover:bg-[#F2E9DF]/90 text-[#14100D] transition"
            >
              <Download className="w-3.5 h-3.5" />
              <span>Download file</span>
            </button>
          </div>
        </div>
      </div>
    </div>
  );
};
