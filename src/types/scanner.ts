export type FindingSeverity = 'critical' | 'high' | 'medium' | 'low' | 'info';

export type FindingCategory =
  | 'dependency'
  | 'hallucination'
  | 'secret'
  | 'code_quality'
  | 'testing';

export interface Finding {
  id: string;
  severity: FindingSeverity;
  effectiveSeverity?: FindingSeverity;
  category: FindingCategory;
  ruleId: string;
  title: string;
  file: string;
  line: number;
  evidence: string; // The exact code snippet or declaration (secrets masked!)
  descriptionRaw: string; // Deterministic factual summary of the rule violation
  confidence?: 'high' | 'medium' | 'low'; // High when from lockfile, medium when resolved via registry max satisfying, low when range minimum fallback
  depScope?: 'runtime' | 'dev'; // Scope of the dependency: runtime or dev dependency
  packageName?: string;
  resolvedVersion?: string;
  advisoryId?: string;
  explanation?: {
    plainEnglishRisk: string; // What it risks in plain English
    nextStep: string;         // What concrete step to take next
    aiFixPrompt?: string;     // Copy-paste prompt for Cursor/Lovable/Bolt
    source: 'gemini' | 'fallback'; // Whether explanation was generated by Gemini or deterministic fallback
  };
}

export interface ScanCoverage {
  totalFilesInRepo: number;
  filesScanned: number;
  totalScannableFiles: number;
  nonScannableSkipped: number;
  isPartial: boolean;
  notes?: string[];
  skippedSummary: {
    overCap: number;
    tooLarge: number;
    binary: number;
    ignoredFolder: number;
  };
}

export interface StackDetection {
  languages: ('javascript' | 'typescript' | 'python')[];
  frameworks: string[];
  manifests: string[];
  hasTests: boolean;
  hasLockfile: boolean;
  totalFilesScanned: number;
  totalLinesScanned: number;
}

export interface RubricScore {
  score: number; // 0 to 100
  grade: 'A' | 'B' | 'C' | 'D' | 'F';
  verdict: 'Healthy' | 'Moderate Risk' | 'Substantial Risk' | 'High Risk' | 'Critical Risk';
  summary: string;
  counts: {
    critical: number;
    high: number;
    medium: number;
    low: number;
    info: number;
    total: number;
  };
  deductions: {
    critical: number;
    high: number;
    medium: number;
    low: number;
  };
}

export interface ScanReport {
  id: string;
  repoUrl: string;
  repoName: string;
  branch: string;
  commitSha?: string;
  scannedAt: string;
  coverage: ScanCoverage;
  stack: StackDetection;
  rubric: RubricScore;
  findings: Finding[];
  executiveSummary: {
    overview: string;
    topThreeFixes: string[];
    vibeAppInsight: string;
    usedFallback?: boolean;
    geminiModelUsed?: string;
  };
  agentRulesCompliant: boolean;
  scanDurationMs: number;
  isSampleRepo?: boolean;
}

export interface ScanProgressUpdate {
  stage: 'fetch' | 'stack' | 'scanning' | 'rubric' | 'explanation' | 'complete' | 'error';
  message: string;
  progressPercent: number;
  scannerName?: string;
}
